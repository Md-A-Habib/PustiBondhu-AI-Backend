package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.core.food.entity.Food;
import com.pustibondhu.backend.health.common.entity.KnowledgeSource;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.util.Objects;

/**
 * Represents an interaction between a {@link Food} and a medicine's active
 * {@link DrugIngredient} (e.g. grapefruit or high-sugar juice timing).
 *
 * <p>Module: HEALTH | Table: food_medicine_interactions | Migration: V100 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>severity: MINOR, MODERATE, MAJOR</li>
 * </ul>
 */
@Entity
@Table(name = "food_medicine_interactions")
public class FoodMedicineInteraction {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Food involved in the interaction (FK -> foods.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "food_id", nullable = false)
    private Food food;

    /** Active ingredient involved (FK -> drug_ingredients.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "ingredient_id", nullable = false)
    private DrugIngredient ingredient;

    /** Severity: MINOR, MODERATE, or MAJOR. */
    @Column(name = "severity", nullable = false, length = 15)
    private String severity;

    /** Effect explanation. */
    @Column(name = "effect", nullable = false, columnDefinition = "TEXT")
    private String effect;

    /** Dietary instruction (optional). */
    @Column(name = "advice", columnDefinition = "TEXT")
    private String advice;

    /** Knowledge source of this data (FK -> knowledge_sources.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "source_id")
    private KnowledgeSource source;

    /** Required by JPA. */
    public FoodMedicineInteraction() {
    }

    /** Creates a fully populated instance. */
    public FoodMedicineInteraction(Long id, Food food, DrugIngredient ingredient, String severity,
                                   String effect, String advice, KnowledgeSource source) {
        this.id = id;
        this.food = food;
        this.ingredient = ingredient;
        this.severity = severity;
        this.effect = effect;
        this.advice = advice;
        this.source = source;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Food getFood() {
        return food;
    }

    public void setFood(Food food) {
        this.food = food;
    }

    public DrugIngredient getIngredient() {
        return ingredient;
    }

    public void setIngredient(DrugIngredient ingredient) {
        this.ingredient = ingredient;
    }

    public String getSeverity() {
        return severity;
    }

    public void setSeverity(String severity) {
        this.severity = severity;
    }

    public String getEffect() {
        return effect;
    }

    public void setEffect(String effect) {
        this.effect = effect;
    }

    public String getAdvice() {
        return advice;
    }

    public void setAdvice(String advice) {
        this.advice = advice;
    }

    public KnowledgeSource getSource() {
        return source;
    }

    public void setSource(KnowledgeSource source) {
        this.source = source;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof FoodMedicineInteraction that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "FoodMedicineInteraction{id=" + id
                + ", severity='" + severity + '\''
                + ", effect='" + effect + '\''
                + ", advice='" + advice + '\'' + '}';
    }
}