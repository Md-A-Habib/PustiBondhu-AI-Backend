package com.pustibondhu.backend.health.activity.entity;

import com.pustibondhu.backend.core.user.entity.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.Instant;
import java.util.Objects;

/**
 * Represents one completed sleep session synced from a {@link HealthConnection}.
 * Replaces the old SleepRecord stub. A row is written only after the sleep ends.
 *
 * <p>Module: HEALTH | Table: sleep_sessions | Migration: V104 | Author: Ahsan</p>
 */
@Entity
@Table(name = "sleep_sessions")
public class SleepSession {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Owner of this session (FK -> users.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /** Source connection (FK -> health_connections.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "connection_id", nullable = false)
    private HealthConnection connection;

    /** Sleep start time (TIMESTAMPTZ). */
    @Column(name = "start_time", nullable = false, columnDefinition = "TIMESTAMPTZ")
    private Instant startTime;

    /** Sleep end time (TIMESTAMPTZ). */
    @Column(name = "end_time", nullable = false, columnDefinition = "TIMESTAMPTZ")
    private Instant endTime;

    /** Total sleep duration in minutes. */
    @Column(name = "duration_minutes", nullable = false)
    private Integer durationMinutes;

    /** Record ID from the platform SDK (optional). */
    @Column(name = "external_record_id", length = 150)
    private String externalRecordId;

    /** Package/ID of the app that produced the data (optional). */
    @Column(name = "source_app", length = 100)
    private String sourceApp;

    /** Required by JPA. */
    public SleepSession() {
    }

    /** Creates a fully populated instance. */
    public SleepSession(Long id, User user, HealthConnection connection, Instant startTime,
                        Instant endTime, Integer durationMinutes, String externalRecordId,
                        String sourceApp) {
        this.id = id;
        this.user = user;
        this.connection = connection;
        this.startTime = startTime;
        this.endTime = endTime;
        this.durationMinutes = durationMinutes;
        this.externalRecordId = externalRecordId;
        this.sourceApp = sourceApp;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public User getUser() {
        return user;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public HealthConnection getConnection() {
        return connection;
    }

    public void setConnection(HealthConnection connection) {
        this.connection = connection;
    }

    public Instant getStartTime() {
        return startTime;
    }

    public void setStartTime(Instant startTime) {
        this.startTime = startTime;
    }

    public Instant getEndTime() {
        return endTime;
    }

    public void setEndTime(Instant endTime) {
        this.endTime = endTime;
    }

    public Integer getDurationMinutes() {
        return durationMinutes;
    }

    public void setDurationMinutes(Integer durationMinutes) {
        this.durationMinutes = durationMinutes;
    }

    public String getExternalRecordId() {
        return externalRecordId;
    }

    public void setExternalRecordId(String externalRecordId) {
        this.externalRecordId = externalRecordId;
    }

    public String getSourceApp() {
        return sourceApp;
    }

    public void setSourceApp(String sourceApp) {
        this.sourceApp = sourceApp;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof SleepSession that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "SleepSession{id=" + id
                + ", startTime=" + startTime
                + ", endTime=" + endTime
                + ", durationMinutes=" + durationMinutes
                + ", externalRecordId='" + externalRecordId + '\''
                + ", sourceApp='" + sourceApp + '\'' + '}';
    }
}