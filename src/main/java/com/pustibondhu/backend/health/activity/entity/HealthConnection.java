package com.pustibondhu.backend.health.activity.entity;

import com.pustibondhu.backend.user.entity.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.Instant;
import java.util.Objects;

/**
 * Represents a user's connection to a health data sync platform
 * (Android Health Connect or Apple HealthKit).
 *
 * <p>Module: HEALTH | Table: health_connections | Migration: V104 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>platform: HEALTH_CONNECT, HEALTHKIT</li>
 *   <li>status: CONNECTED, REVOKED, ERROR</li>
 * </ul>
 */
@Entity
@Table(name = "health_connections")
public class HealthConnection {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Owner of this connection (FK -> users.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /** Sync platform: HEALTH_CONNECT or HEALTHKIT. */
    @Column(name = "platform", nullable = false, length = 20)
    private String platform;

    /** Smartwatch / phone device name (optional). */
    @Column(name = "device_name", length = 120)
    private String deviceName;

    /** Connection status: CONNECTED, REVOKED, or ERROR. */
    @Column(name = "status", nullable = false, length = 12)
    private String status;

    /** Timestamp of the last successful sync (TIMESTAMPTZ, optional). */
    @Column(name = "last_synced_at", columnDefinition = "TIMESTAMPTZ")
    private Instant lastSyncedAt;

    /** Required by JPA. */
    public HealthConnection() {
    }

    /** Creates a fully populated instance. */
    public HealthConnection(Long id, User user, String platform, String deviceName,
                            String status, Instant lastSyncedAt) {
        this.id = id;
        this.user = user;
        this.platform = platform;
        this.deviceName = deviceName;
        this.status = status;
        this.lastSyncedAt = lastSyncedAt;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public User getUser() {
        return user;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public String getPlatform() {
        return platform;
    }

    public void setPlatform(String platform) {
        this.platform = platform;
    }

    public String getDeviceName() {
        return deviceName;
    }

    public void setDeviceName(String deviceName) {
        this.deviceName = deviceName;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public Instant getLastSyncedAt() {
        return lastSyncedAt;
    }

    public void setLastSyncedAt(Instant lastSyncedAt) {
        this.lastSyncedAt = lastSyncedAt;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof HealthConnection that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "HealthConnection{id=" + id
                + ", platform='" + platform + '\''
                + ", deviceName='" + deviceName + '\''
                + ", status='" + status + '\''
                + ", lastSyncedAt=" + lastSyncedAt + '}';
    }
}