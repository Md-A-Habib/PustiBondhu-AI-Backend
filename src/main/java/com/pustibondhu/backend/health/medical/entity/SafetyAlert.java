package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.core.user.entity.User;
import com.pustibondhu.backend.health.common.entity.KnowledgeSource;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.Instant;
import java.util.Objects;

/**
 * Represents a safety alert shown to a user. An alert can be triggered by a
 * {@link FoodMedicineInteraction}, a {@link DrugInteraction}, or a critical
 * {@link LabResult}; only the matching reference is filled.
 *
 * <p>Module: HEALTH | Table: safety_alerts | Migration: V103 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>alert_type: FOOD_MEDICINE, DRUG_DRUG, LAB_CRITICAL</li>
 *   <li>severity: INFO, WARNING, URGENT</li>
 *   <li>acknowledged_at: null means the user has not read the alert yet</li>
 * </ul>
 */
@Entity
@Table(name = "safety_alerts")
public class SafetyAlert {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Alert recipient (FK -> users.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /** Alert type: FOOD_MEDICINE, DRUG_DRUG, or LAB_CRITICAL. */
    @Column(name = "alert_type", nullable = false, length = 20)
    private String alertType;

    /** Severity: INFO, WARNING, or URGENT. */
    @Column(name = "severity", nullable = false, length = 10)
    private String severity;

    /** Alert message shown to the user. */
    @Column(name = "message", nullable = false, columnDefinition = "TEXT")
    private String message;

    /** Triggering food-medicine interaction (FK -> food_medicine_interactions.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "food_medicine_interaction_id")
    private FoodMedicineInteraction foodMedicineInteraction;

    /** Triggering drug-drug interaction (FK -> drug_interactions.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "drug_interaction_id")
    private DrugInteraction drugInteraction;

    /** Triggering lab result (FK -> lab_results.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "lab_result_id")
    private LabResult labResult;

    /** Knowledge source of this alert (FK -> knowledge_sources.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "source_id")
    private KnowledgeSource source;

    /** Time the user acknowledged the alert (TIMESTAMPTZ, optional). */
    @Column(name = "acknowledged_at", columnDefinition = "TIMESTAMPTZ")
    private Instant acknowledgedAt;

    /** Required by JPA. */
    public SafetyAlert() {
    }

    /** Creates a fully populated instance. */
    public SafetyAlert(Long id, User user, String alertType, String severity, String message,
                       FoodMedicineInteraction foodMedicineInteraction,
                       DrugInteraction drugInteraction, LabResult labResult,
                       KnowledgeSource source, Instant acknowledgedAt) {
        this.id = id;
        this.user = user;
        this.alertType = alertType;
        this.severity = severity;
        this.message = message;
        this.foodMedicineInteraction = foodMedicineInteraction;
        this.drugInteraction = drugInteraction;
        this.labResult = labResult;
        this.source = source;
        this.acknowledgedAt = acknowledgedAt;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public User getUser() {
        return user;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public String getAlertType() {
        return alertType;
    }

    public void setAlertType(String alertType) {
        this.alertType = alertType;
    }

    public String getSeverity() {
        return severity;
    }

    public void setSeverity(String severity) {
        this.severity = severity;
    }

    public String getMessage() {
        return message;
    }

    public void setMessage(String message) {
        this.message = message;
    }

    public FoodMedicineInteraction getFoodMedicineInteraction() {
        return foodMedicineInteraction;
    }

    public void setFoodMedicineInteraction(FoodMedicineInteraction foodMedicineInteraction) {
        this.foodMedicineInteraction = foodMedicineInteraction;
    }

    public DrugInteraction getDrugInteraction() {
        return drugInteraction;
    }

    public void setDrugInteraction(DrugInteraction drugInteraction) {
        this.drugInteraction = drugInteraction;
    }

    public LabResult getLabResult() {
        return labResult;
    }

    public void setLabResult(LabResult labResult) {
        this.labResult = labResult;
    }

    public KnowledgeSource getSource() {
        return source;
    }

    public void setSource(KnowledgeSource source) {
        this.source = source;
    }

    public Instant getAcknowledgedAt() {
        return acknowledgedAt;
    }

    public void setAcknowledgedAt(Instant acknowledgedAt) {
        this.acknowledgedAt = acknowledgedAt;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof SafetyAlert that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "SafetyAlert{id=" + id
                + ", alertType='" + alertType + '\''
                + ", severity='" + severity + '\''
                + ", message='" + message + '\''
                + ", acknowledgedAt=" + acknowledgedAt + '}';
    }
}