package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.core.food.entity.Food;
import com.pustibondhu.backend.health.common.entity.KnowledgeSource;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.math.BigDecimal;
import java.util.Objects;

/**
 * Represents a dietary rule linking a {@link Food} to a {@link MedicalCondition}
 * with a safety tier. Moved from Core to Health because it references medical_conditions.
 *
 * <p>Module: HEALTH | Table: food_condition_rules | Migration: V100 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>tier: SAFE, RESTRICT, AVOID</li>
 *   <li>unit: g, ml, serving</li>
 * </ul>
 */
@Entity
@Table(name = "food_condition_rules")
public class FoodConditionRule {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Food this rule applies to (FK -> foods.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "food_id", nullable = false)
    private Food food;

    /** Medical condition this rule applies to (FK -> medical_conditions.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "condition_id", nullable = false)
    private MedicalCondition condition;

    /** Safety tier: SAFE, RESTRICT, or AVOID. */
    @Column(name = "tier", nullable = false, length = 10)
    private String tier;

    /** Maximum allowed amount per day, NUMERIC(8,2) (optional). */
    @Column(name = "max_amount_per_day", precision = 8, scale = 2)
    private BigDecimal maxAmountPerDay;

    /** Unit of the max amount: g, ml, or serving (optional). */
    @Column(name = "unit", length = 10)
    private String unit;

    /** Explanation shown to the user (optional). */
    @Column(name = "explanation", columnDefinition = "TEXT")
    private String explanation;

    /** Knowledge source of this rule (FK -> knowledge_sources.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "source_id")
    private KnowledgeSource source;

    /** Required by JPA. */
    public FoodConditionRule() {
    }

    /** Creates a fully populated instance. */
    public FoodConditionRule(Long id, Food food, MedicalCondition condition, String tier,
                             BigDecimal maxAmountPerDay, String unit, String explanation,
                             KnowledgeSource source) {
        this.id = id;
        this.food = food;
        this.condition = condition;
        this.tier = tier;
        this.maxAmountPerDay = maxAmountPerDay;
        this.unit = unit;
        this.explanation = explanation;
        this.source = source;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Food getFood() {
        return food;
    }

    public void setFood(Food food) {
        this.food = food;
    }

    public MedicalCondition getCondition() {
        return condition;
    }

    public void setCondition(MedicalCondition condition) {
        this.condition = condition;
    }

    public String getTier() {
        return tier;
    }

    public void setTier(String tier) {
        this.tier = tier;
    }

    public BigDecimal getMaxAmountPerDay() {
        return maxAmountPerDay;
    }

    public void setMaxAmountPerDay(BigDecimal maxAmountPerDay) {
        this.maxAmountPerDay = maxAmountPerDay;
    }

    public String getUnit() {
        return unit;
    }

    public void setUnit(String unit) {
        this.unit = unit;
    }

    public String getExplanation() {
        return explanation;
    }

    public void setExplanation(String explanation) {
        this.explanation = explanation;
    }

    public KnowledgeSource getSource() {
        return source;
    }

    public void setSource(KnowledgeSource source) {
        this.source = source;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof FoodConditionRule that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "FoodConditionRule{id=" + id
                + ", tier='" + tier + '\''
                + ", maxAmountPerDay=" + maxAmountPerDay
                + ", unit='" + unit + '\''
                + ", explanation='" + explanation + '\'' + '}';
    }
}