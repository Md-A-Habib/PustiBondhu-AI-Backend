package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.health.common.entity.KnowledgeSource;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.util.Objects;

/**
 * Represents a commercial brand medicine sold locally.
 *
 * <p>Module: HEALTH | Table: medicines | Migration: V100 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>dosage_form: TABLET, SYRUP, INJECTION</li>
 *   <li>is_prescription: true if the medicine requires a prescription</li>
 * </ul>
 */
@Entity
@Table(name = "medicines")
public class Medicine {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Brand product name. */
    @Column(name = "brand_name", nullable = false, length = 150)
    private String brandName;

    /** Pharma company name (optional). */
    @Column(name = "manufacturer", length = 150)
    private String manufacturer;

    /** Strength, e.g. 500 mg (optional). */
    @Column(name = "strength", length = 50)
    private String strength;

    /** Dosage form: TABLET, SYRUP, INJECTION (optional). */
    @Column(name = "dosage_form", length = 40)
    private String dosageForm;

    /** Whether the medicine requires a prescription. */
    @Column(name = "is_prescription", nullable = false)
    private Boolean isPrescription;

    /** Knowledge source of this data (FK -> knowledge_sources.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "source_id")
    private KnowledgeSource source;

    /** Required by JPA. */
    public Medicine() {
    }

    /** Creates a fully populated instance. */
    public Medicine(Long id, String brandName, String manufacturer, String strength,
                    String dosageForm, Boolean isPrescription, KnowledgeSource source) {
        this.id = id;
        this.brandName = brandName;
        this.manufacturer = manufacturer;
        this.strength = strength;
        this.dosageForm = dosageForm;
        this.isPrescription = isPrescription;
        this.source = source;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getBrandName() {
        return brandName;
    }

    public void setBrandName(String brandName) {
        this.brandName = brandName;
    }

    public String getManufacturer() {
        return manufacturer;
    }

    public void setManufacturer(String manufacturer) {
        this.manufacturer = manufacturer;
    }

    public String getStrength() {
        return strength;
    }

    public void setStrength(String strength) {
        this.strength = strength;
    }

    public String getDosageForm() {
        return dosageForm;
    }

    public void setDosageForm(String dosageForm) {
        this.dosageForm = dosageForm;
    }

    public Boolean getIsPrescription() {
        return isPrescription;
    }

    public void setIsPrescription(Boolean isPrescription) {
        this.isPrescription = isPrescription;
    }

    public KnowledgeSource getSource() {
        return source;
    }

    public void setSource(KnowledgeSource source) {
        this.source = source;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Medicine that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "Medicine{id=" + id
                + ", brandName='" + brandName + '\''
                + ", manufacturer='" + manufacturer + '\''
                + ", strength='" + strength + '\''
                + ", dosageForm='" + dosageForm + '\''
                + ", isPrescription=" + isPrescription + '}';
    }
}