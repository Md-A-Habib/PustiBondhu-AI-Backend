package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.core.user.entity.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.LocalDate;
import java.util.Objects;

/**
 * Maps an active diagnosed {@link MedicalCondition} to a user.
 *
 * <p>Module: HEALTH | Table: user_conditions | Migration: V101 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>status: ACTIVE, CONTROLLED</li>
 *   <li>source: MANUAL, EXTRACTED</li>
 * </ul>
 */
@Entity
@Table(name = "user_conditions")
public class UserCondition {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Owner of this record (FK -> users.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /** Diagnosed condition (FK -> medical_conditions.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "condition_id", nullable = false)
    private MedicalCondition condition;

    /** Diagnosis date (optional). */
    @Column(name = "diagnosed_on")
    private LocalDate diagnosedOn;

    /** Status: ACTIVE or CONTROLLED. */
    @Column(name = "status", nullable = false, length = 15)
    private String status;

    /** How the record was added: MANUAL or EXTRACTED. */
    @Column(name = "source", nullable = false, length = 10)
    private String source;

    /** Extraction this record came from (FK -> document_extractions.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "extraction_id")
    private DocumentExtraction extraction;

    /** Required by JPA. */
    public UserCondition() {
    }

    /** Creates a fully populated instance. */
    public UserCondition(Long id, User user, MedicalCondition condition, LocalDate diagnosedOn,
                         String status, String source, DocumentExtraction extraction) {
        this.id = id;
        this.user = user;
        this.condition = condition;
        this.diagnosedOn = diagnosedOn;
        this.status = status;
        this.source = source;
        this.extraction = extraction;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public User getUser() {
        return user;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public MedicalCondition getCondition() {
        return condition;
    }

    public void setCondition(MedicalCondition condition) {
        this.condition = condition;
    }

    public LocalDate getDiagnosedOn() {
        return diagnosedOn;
    }

    public void setDiagnosedOn(LocalDate diagnosedOn) {
        this.diagnosedOn = diagnosedOn;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getSource() {
        return source;
    }

    public void setSource(String source) {
        this.source = source;
    }

    public DocumentExtraction getExtraction() {
        return extraction;
    }

    public void setExtraction(DocumentExtraction extraction) {
        this.extraction = extraction;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof UserCondition that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "UserCondition{id=" + id
                + ", diagnosedOn=" + diagnosedOn
                + ", status='" + status + '\''
                + ", source='" + source + '\'' + '}';
    }
}