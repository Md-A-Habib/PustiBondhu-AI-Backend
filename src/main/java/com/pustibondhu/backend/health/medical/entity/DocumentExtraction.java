package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.core.ai.entity.AiJob;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.Objects;

/**
 * Stores an AI OCR extraction of a {@link MedicalDocument}, pending user confirmation.
 *
 * <p>Module: HEALTH | Table: document_extractions | Migration: V101 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>review_status: PENDING_REVIEW, CONFIRMED</li>
 *   <li>extracted_payload: raw extracted data stored as JSONB</li>
 * </ul>
 */
@Entity
@Table(name = "document_extractions")
public class DocumentExtraction {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Source document (FK -> medical_documents.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "document_id", nullable = false)
    private MedicalDocument document;

    /** AI job that produced this extraction (FK -> ai_jobs.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "job_id")
    private AiJob job;

    /** Extracted data as a JSON string (JSONB). */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "extracted_payload", nullable = false, columnDefinition = "JSONB")
    private String extractedPayload;

    /** AI model version (optional). */
    @Column(name = "model_version", length = 60)
    private String modelVersion;

    /** Confidence score, NUMERIC(4,3) (optional). */
    @Column(name = "confidence", precision = 4, scale = 3)
    private BigDecimal confidence;

    /** Review status: PENDING_REVIEW or CONFIRMED. */
    @Column(name = "review_status", nullable = false, length = 15)
    private String reviewStatus;

    /** Time the user confirmed the extraction (TIMESTAMPTZ, optional). */
    @Column(name = "confirmed_at", columnDefinition = "TIMESTAMPTZ")
    private Instant confirmedAt;

    /** Required by JPA. */
    public DocumentExtraction() {
    }

    /** Creates a fully populated instance. */
    public DocumentExtraction(Long id, MedicalDocument document, AiJob job, String extractedPayload,
                              String modelVersion, BigDecimal confidence, String reviewStatus,
                              Instant confirmedAt) {
        this.id = id;
        this.document = document;
        this.job = job;
        this.extractedPayload = extractedPayload;
        this.modelVersion = modelVersion;
        this.confidence = confidence;
        this.reviewStatus = reviewStatus;
        this.confirmedAt = confirmedAt;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public MedicalDocument getDocument() {
        return document;
    }

    public void setDocument(MedicalDocument document) {
        this.document = document;
    }

    public AiJob getJob() {
        return job;
    }

    public void setJob(AiJob job) {
        this.job = job;
    }

    public String getExtractedPayload() {
        return extractedPayload;
    }

    public void setExtractedPayload(String extractedPayload) {
        this.extractedPayload = extractedPayload;
    }

    public String getModelVersion() {
        return modelVersion;
    }

    public void setModelVersion(String modelVersion) {
        this.modelVersion = modelVersion;
    }

    public BigDecimal getConfidence() {
        return confidence;
    }

    public void setConfidence(BigDecimal confidence) {
        this.confidence = confidence;
    }

    public String getReviewStatus() {
        return reviewStatus;
    }

    public void setReviewStatus(String reviewStatus) {
        this.reviewStatus = reviewStatus;
    }

    public Instant getConfirmedAt() {
        return confirmedAt;
    }

    public void setConfirmedAt(Instant confirmedAt) {
        this.confirmedAt = confirmedAt;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof DocumentExtraction that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "DocumentExtraction{id=" + id
                + ", modelVersion='" + modelVersion + '\''
                + ", confidence=" + confidence
                + ", reviewStatus='" + reviewStatus + '\''
                + ", confirmedAt=" + confirmedAt + '}';
    }
}
