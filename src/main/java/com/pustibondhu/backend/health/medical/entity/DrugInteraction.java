package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.health.common.entity.KnowledgeSource;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.util.Objects;

/**
 * Represents a drug-to-drug interaction warning between two
 * {@link DrugIngredient} records.
 *
 * <p>Module: HEALTH | Table: drug_interactions | Migration: V100 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>severity: MINOR, MODERATE, MAJOR</li>
 * </ul>
 */
@Entity
@Table(name = "drug_interactions")
public class DrugInteraction {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** First ingredient (FK -> drug_ingredients.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "ingredient_a_id", nullable = false)
    private DrugIngredient ingredientA;

    /** Second ingredient (FK -> drug_ingredients.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "ingredient_b_id", nullable = false)
    private DrugIngredient ingredientB;

    /** Severity: MINOR, MODERATE, or MAJOR. */
    @Column(name = "severity", nullable = false, length = 15)
    private String severity;

    /** Interaction mechanism / effect. */
    @Column(name = "effect", nullable = false, columnDefinition = "TEXT")
    private String effect;

    /** Medical advice (optional). */
    @Column(name = "advice", columnDefinition = "TEXT")
    private String advice;

    /** Knowledge source of this data (FK -> knowledge_sources.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "source_id")
    private KnowledgeSource source;

    /** Required by JPA. */
    public DrugInteraction() {
    }

    /** Creates a fully populated instance. */
    public DrugInteraction(Long id, DrugIngredient ingredientA, DrugIngredient ingredientB,
                           String severity, String effect, String advice, KnowledgeSource source) {
        this.id = id;
        this.ingredientA = ingredientA;
        this.ingredientB = ingredientB;
        this.severity = severity;
        this.effect = effect;
        this.advice = advice;
        this.source = source;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public DrugIngredient getIngredientA() {
        return ingredientA;
    }

    public void setIngredientA(DrugIngredient ingredientA) {
        this.ingredientA = ingredientA;
    }

    public DrugIngredient getIngredientB() {
        return ingredientB;
    }

    public void setIngredientB(DrugIngredient ingredientB) {
        this.ingredientB = ingredientB;
    }

    public String getSeverity() {
        return severity;
    }

    public void setSeverity(String severity) {
        this.severity = severity;
    }

    public String getEffect() {
        return effect;
    }

    public void setEffect(String effect) {
        this.effect = effect;
    }

    public String getAdvice() {
        return advice;
    }

    public void setAdvice(String advice) {
        this.advice = advice;
    }

    public KnowledgeSource getSource() {
        return source;
    }

    public void setSource(KnowledgeSource source) {
        this.source = source;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof DrugInteraction that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "DrugInteraction{id=" + id
                + ", severity='" + severity + '\''
                + ", effect='" + effect + '\''
                + ", advice='" + advice + '\'' + '}';
    }
}