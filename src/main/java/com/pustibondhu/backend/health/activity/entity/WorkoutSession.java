package com.pustibondhu.backend.health.activity.entity;

import com.pustibondhu.backend.core.user.entity.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.Objects;

/**
 * Represents one exercise workout (WALKING, RUNNING, CYCLING) synced from a
 * {@link HealthConnection}.
 *
 * <p>Module: HEALTH | Table: workout_sessions | Migration: V104 | Author: Ahsan</p>
 */
@Entity
@Table(name = "workout_sessions")
public class WorkoutSession {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Owner of this workout (FK -> users.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /** Source connection (FK -> health_connections.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "connection_id", nullable = false)
    private HealthConnection connection;

    /** Exercise type: WALKING, RUNNING, or CYCLING. */
    @Column(name = "exercise_type", nullable = false, length = 40)
    private String exerciseType;

    /** Workout start time (TIMESTAMPTZ). */
    @Column(name = "start_time", nullable = false, columnDefinition = "TIMESTAMPTZ")
    private Instant startTime;

    /** Workout end time (TIMESTAMPTZ). */
    @Column(name = "end_time", nullable = false, columnDefinition = "TIMESTAMPTZ")
    private Instant endTime;

    /** Calories burned, NUMERIC(8,2) (optional). */
    @Column(name = "active_energy_kcal", precision = 8, scale = 2)
    private BigDecimal activeEnergyKcal;

    /** Distance in meters, NUMERIC(10,2) (optional). */
    @Column(name = "distance_m", precision = 10, scale = 2)
    private BigDecimal distanceM;

    /** Record ID from the platform SDK (optional). */
    @Column(name = "external_record_id", length = 150)
    private String externalRecordId;

    /** Required by JPA. */
    public WorkoutSession() {
    }

    /** Creates a fully populated instance. */
    public WorkoutSession(Long id, User user, HealthConnection connection, String exerciseType,
                          Instant startTime, Instant endTime, BigDecimal activeEnergyKcal,
                          BigDecimal distanceM, String externalRecordId) {
        this.id = id;
        this.user = user;
        this.connection = connection;
        this.exerciseType = exerciseType;
        this.startTime = startTime;
        this.endTime = endTime;
        this.activeEnergyKcal = activeEnergyKcal;
        this.distanceM = distanceM;
        this.externalRecordId = externalRecordId;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public User getUser() {
        return user;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public HealthConnection getConnection() {
        return connection;
    }

    public void setConnection(HealthConnection connection) {
        this.connection = connection;
    }

    public String getExerciseType() {
        return exerciseType;
    }

    public void setExerciseType(String exerciseType) {
        this.exerciseType = exerciseType;
    }

    public Instant getStartTime() {
        return startTime;
    }

    public void setStartTime(Instant startTime) {
        this.startTime = startTime;
    }

    public Instant getEndTime() {
        return endTime;
    }

    public void setEndTime(Instant endTime) {
        this.endTime = endTime;
    }

    public BigDecimal getActiveEnergyKcal() {
        return activeEnergyKcal;
    }

    public void setActiveEnergyKcal(BigDecimal activeEnergyKcal) {
        this.activeEnergyKcal = activeEnergyKcal;
    }

    public BigDecimal getDistanceM() {
        return distanceM;
    }

    public void setDistanceM(BigDecimal distanceM) {
        this.distanceM = distanceM;
    }

    public String getExternalRecordId() {
        return externalRecordId;
    }

    public void setExternalRecordId(String externalRecordId) {
        this.externalRecordId = externalRecordId;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof WorkoutSession that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "WorkoutSession{id=" + id
                + ", exerciseType='" + exerciseType + '\''
                + ", startTime=" + startTime
                + ", endTime=" + endTime
                + ", activeEnergyKcal=" + activeEnergyKcal
                + ", distanceM=" + distanceM
                + ", externalRecordId='" + externalRecordId + '\'' + '}';
    }
}