package com.pustibondhu.backend.health.medical.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

import java.util.Objects;

/**
 * Registry of key medical lab metrics (e.g. HBA1C, FBS, LDL).
 *
 * <p>Module: HEALTH | Table: lab_test_definitions | Migration: V102 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>code: unique test code</li>
 *   <li>category: DIABETES, LIPID, KIDNEY</li>
 * </ul>
 */
@Entity
@Table(name = "lab_test_definitions")
public class LabTestDefinition {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Unique test code. */
    @Column(name = "code", nullable = false, unique = true, length = 30)
    private String code;

    /** English name. */
    @Column(name = "name_en", nullable = false, length = 150)
    private String nameEn;

    /** Bangla name. */
    @Column(name = "name_bn", nullable = false, length = 150)
    private String nameBn;

    /** Default measurement unit (optional). */
    @Column(name = "default_unit", length = 30)
    private String defaultUnit;

    /** Category: DIABETES, LIPID, KIDNEY. */
    @Column(name = "category", nullable = false, length = 40)
    private String category;

    /** Required by JPA. */
    public LabTestDefinition() {
    }

    /** Creates a fully populated instance. */
    public LabTestDefinition(Long id, String code, String nameEn, String nameBn,
                             String defaultUnit, String category) {
        this.id = id;
        this.code = code;
        this.nameEn = nameEn;
        this.nameBn = nameBn;
        this.defaultUnit = defaultUnit;
        this.category = category;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
    }

    public String getNameEn() {
        return nameEn;
    }

    public void setNameEn(String nameEn) {
        this.nameEn = nameEn;
    }

    public String getNameBn() {
        return nameBn;
    }

    public void setNameBn(String nameBn) {
        this.nameBn = nameBn;
    }

    public String getDefaultUnit() {
        return defaultUnit;
    }

    public void setDefaultUnit(String defaultUnit) {
        this.defaultUnit = defaultUnit;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof LabTestDefinition that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "LabTestDefinition{id=" + id
                + ", code='" + code + '\''
                + ", nameEn='" + nameEn + '\''
                + ", nameBn='" + nameBn + '\''
                + ", defaultUnit='" + defaultUnit + '\''
                + ", category='" + category + '\'' + '}';
    }
}