package com.pustibondhu.backend.health.activity.entity;

import com.pustibondhu.backend.user.entity.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.Objects;

/**
 * Represents one activity measurement (steps, active energy, heart rate)
 * synced from a {@link HealthConnection}. Replaces the old ActivityRecord stub.
 *
 * <p>Module: HEALTH | Table: activity_samples | Migration: V104 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>metric_type: STEPS, ACTIVE_ENERGY, HEART_RATE</li>
 *   <li>unit: count, kcal, bpm</li>
 *   <li>external_record_id is unique per connection (used to avoid duplicate syncs)</li>
 * </ul>
 */
@Entity
@Table(
        name = "activity_samples",
        uniqueConstraints = @UniqueConstraint(
                name = "uq_activity_samples_connection_external",
                columnNames = {"connection_id", "external_record_id"}
        )
)
public class ActivitySample {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Owner of this sample (FK -> users.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /** Source connection (FK -> health_connections.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "connection_id", nullable = false)
    private HealthConnection connection;

    /** Metric type: STEPS, ACTIVE_ENERGY, or HEART_RATE. */
    @Column(name = "metric_type", nullable = false, length = 30)
    private String metricType;

    /** Measurement value, NUMERIC(10,2). */
    @Column(name = "value", nullable = false, precision = 10, scale = 2)
    private BigDecimal value;

    /** Unit of the value: count, kcal, or bpm. */
    @Column(name = "unit", nullable = false, length = 15)
    private String unit;

    /** Start of the measurement window (TIMESTAMPTZ). */
    @Column(name = "start_time", nullable = false, columnDefinition = "TIMESTAMPTZ")
    private Instant startTime;

    /** End of the measurement window (TIMESTAMPTZ). */
    @Column(name = "end_time", nullable = false, columnDefinition = "TIMESTAMPTZ")
    private Instant endTime;

    /** Record ID from the platform SDK (optional, unique per connection). */
    @Column(name = "external_record_id", length = 150)
    private String externalRecordId;

    /** Record version from the platform SDK (optional). */
    @Column(name = "client_record_version")
    private Long clientRecordVersion;

    /** Package/ID of the app that produced the data (optional). */
    @Column(name = "source_app", length = 100)
    private String sourceApp;

    /** Required by JPA. */
    public ActivitySample() {
    }

    /** Creates a fully populated instance. */
    public ActivitySample(Long id, User user, HealthConnection connection, String metricType,
                          BigDecimal value, String unit, Instant startTime, Instant endTime,
                          String externalRecordId, Long clientRecordVersion, String sourceApp) {
        this.id = id;
        this.user = user;
        this.connection = connection;
        this.metricType = metricType;
        this.value = value;
        this.unit = unit;
        this.startTime = startTime;
        this.endTime = endTime;
        this.externalRecordId = externalRecordId;
        this.clientRecordVersion = clientRecordVersion;
        this.sourceApp = sourceApp;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public User getUser() {
        return user;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public HealthConnection getConnection() {
        return connection;
    }

    public void setConnection(HealthConnection connection) {
        this.connection = connection;
    }

    public String getMetricType() {
        return metricType;
    }

    public void setMetricType(String metricType) {
        this.metricType = metricType;
    }

    public BigDecimal getValue() {
        return value;
    }

    public void setValue(BigDecimal value) {
        this.value = value;
    }

    public String getUnit() {
        return unit;
    }

    public void setUnit(String unit) {
        this.unit = unit;
    }

    public Instant getStartTime() {
        return startTime;
    }

    public void setStartTime(Instant startTime) {
        this.startTime = startTime;
    }

    public Instant getEndTime() {
        return endTime;
    }

    public void setEndTime(Instant endTime) {
        this.endTime = endTime;
    }

    public String getExternalRecordId() {
        return externalRecordId;
    }

    public void setExternalRecordId(String externalRecordId) {
        this.externalRecordId = externalRecordId;
    }

    public Long getClientRecordVersion() {
        return clientRecordVersion;
    }

    public void setClientRecordVersion(Long clientRecordVersion) {
        this.clientRecordVersion = clientRecordVersion;
    }

    public String getSourceApp() {
        return sourceApp;
    }

    public void setSourceApp(String sourceApp) {
        this.sourceApp = sourceApp;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof ActivitySample that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "ActivitySample{id=" + id
                + ", metricType='" + metricType + '\''
                + ", value=" + value
                + ", unit='" + unit + '\''
                + ", startTime=" + startTime
                + ", endTime=" + endTime
                + ", externalRecordId='" + externalRecordId + '\''
                + ", clientRecordVersion=" + clientRecordVersion
                + ", sourceApp='" + sourceApp + '\'' + '}';
    }
}