package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.health.common.entity.KnowledgeSource;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import java.math.BigDecimal;
import java.util.Objects;

/**
 * Represents normal physiological reference boundaries of a
 * {@link LabTestDefinition}, by sex, age range and life stage.
 *
 * <p>Module: HEALTH | Table: lab_reference_ranges | Migration: V102 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>sex: MALE, FEMALE, ANY</li>
 *   <li>life_stage: PREGNANT, NONE</li>
 * </ul>
 */
@Entity
@Table(name = "lab_reference_ranges")
public class LabReferenceRange {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Lab test this range belongs to (FK -> lab_test_definitions.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "lab_test_id", nullable = false)
    private LabTestDefinition labTest;

    /** Sex: MALE, FEMALE, or ANY. */
    @Column(name = "sex", nullable = false, length = 10)
    private String sex;

    /** Minimum age, SMALLINT (optional). */
    @JdbcTypeCode(SqlTypes.SMALLINT)
    @Column(name = "age_min")
    private Integer ageMin;

    /** Maximum age, SMALLINT (optional). */
    @JdbcTypeCode(SqlTypes.SMALLINT)
    @Column(name = "age_max")
    private Integer ageMax;

    /** Life stage: PREGNANT or NONE (optional). */
    @Column(name = "life_stage", length = 20)
    private String lifeStage;

    /** Lower bound, NUMERIC(10,3) (optional). */
    @Column(name = "low_value", precision = 10, scale = 3)
    private BigDecimal lowValue;

    /** Upper bound, NUMERIC(10,3) (optional). */
    @Column(name = "high_value", precision = 10, scale = 3)
    private BigDecimal highValue;

    /** Unit string (optional). */
    @Column(name = "unit", length = 30)
    private String unit;

    /** Knowledge source of this range (FK -> knowledge_sources.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "source_id")
    private KnowledgeSource source;

    /** Required by JPA. */
    public LabReferenceRange() {
    }

    /** Creates a fully populated instance. */
    public LabReferenceRange(Long id, LabTestDefinition labTest, String sex, Integer ageMin,
                             Integer ageMax, String lifeStage, BigDecimal lowValue,
                             BigDecimal highValue, String unit, KnowledgeSource source) {
        this.id = id;
        this.labTest = labTest;
        this.sex = sex;
        this.ageMin = ageMin;
        this.ageMax = ageMax;
        this.lifeStage = lifeStage;
        this.lowValue = lowValue;
        this.highValue = highValue;
        this.unit = unit;
        this.source = source;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public LabTestDefinition getLabTest() {
        return labTest;
    }

    public void setLabTest(LabTestDefinition labTest) {
        this.labTest = labTest;
    }

    public String getSex() {
        return sex;
    }

    public void setSex(String sex) {
        this.sex = sex;
    }

    public Integer getAgeMin() {
        return ageMin;
    }

    public void setAgeMin(Integer ageMin) {
        this.ageMin = ageMin;
    }

    public Integer getAgeMax() {
        return ageMax;
    }

    public void setAgeMax(Integer ageMax) {
        this.ageMax = ageMax;
    }

    public String getLifeStage() {
        return lifeStage;
    }

    public void setLifeStage(String lifeStage) {
        this.lifeStage = lifeStage;
    }

    public BigDecimal getLowValue() {
        return lowValue;
    }

    public void setLowValue(BigDecimal lowValue) {
        this.lowValue = lowValue;
    }

    public BigDecimal getHighValue() {
        return highValue;
    }

    public void setHighValue(BigDecimal highValue) {
        this.highValue = highValue;
    }

    public String getUnit() {
        return unit;
    }

    public void setUnit(String unit) {
        this.unit = unit;
    }

    public KnowledgeSource getSource() {
        return source;
    }

    public void setSource(KnowledgeSource source) {
        this.source = source;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof LabReferenceRange that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "LabReferenceRange{id=" + id
                + ", sex='" + sex + '\''
                + ", ageMin=" + ageMin
                + ", ageMax=" + ageMax
                + ", lifeStage='" + lifeStage + '\''
                + ", lowValue=" + lowValue
                + ", highValue=" + highValue
                + ", unit='" + unit + '\'' + '}';
    }
}