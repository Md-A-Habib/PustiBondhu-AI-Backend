package com.pustibondhu.backend.health.activity.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.Instant;
import java.util.Objects;

/**
 * Represents a granular permission for one metric type (e.g. STEPS, HEART_RATE, SLEEP)
 * under a specific {@link HealthConnection}.
 *
 * <p>Module: HEALTH | Table: health_permissions | Migration: V104 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>metric_type: STEPS, HEART_RATE, SLEEP</li>
 *   <li>granted: true if the user currently allows this metric to be synced</li>
 * </ul>
 */
@Entity
@Table(name = "health_permissions")
public class HealthPermission {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Parent connection (FK -> health_connections.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "connection_id", nullable = false)
    private HealthConnection connection;

    /** Metric type: STEPS, HEART_RATE, or SLEEP. */
    @Column(name = "metric_type", nullable = false, length = 30)
    private String metricType;

    /** Whether the permission is currently granted. */
    @Column(name = "granted", nullable = false)
    private Boolean granted;

    /** Timestamp when the permission was granted (TIMESTAMPTZ, optional). */
    @Column(name = "granted_at", columnDefinition = "TIMESTAMPTZ")
    private Instant grantedAt;

    /** Timestamp when the permission was revoked (TIMESTAMPTZ, optional). */
    @Column(name = "revoked_at", columnDefinition = "TIMESTAMPTZ")
    private Instant revokedAt;

    /** Required by JPA. */
    public HealthPermission() {
    }

    /** Creates a fully populated instance. */
    public HealthPermission(Long id, HealthConnection connection, String metricType,
                            Boolean granted, Instant grantedAt, Instant revokedAt) {
        this.id = id;
        this.connection = connection;
        this.metricType = metricType;
        this.granted = granted;
        this.grantedAt = grantedAt;
        this.revokedAt = revokedAt;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public HealthConnection getConnection() {
        return connection;
    }

    public void setConnection(HealthConnection connection) {
        this.connection = connection;
    }

    public String getMetricType() {
        return metricType;
    }

    public void setMetricType(String metricType) {
        this.metricType = metricType;
    }

    public Boolean getGranted() {
        return granted;
    }

    public void setGranted(Boolean granted) {
        this.granted = granted;
    }

    public Instant getGrantedAt() {
        return grantedAt;
    }

    public void setGrantedAt(Instant grantedAt) {
        this.grantedAt = grantedAt;
    }

    public Instant getRevokedAt() {
        return revokedAt;
    }

    public void setRevokedAt(Instant revokedAt) {
        this.revokedAt = revokedAt;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof HealthPermission that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "HealthPermission{id=" + id
                + ", metricType='" + metricType + '\''
                + ", granted=" + granted
                + ", grantedAt=" + grantedAt
                + ", revokedAt=" + revokedAt + '}';
    }
}