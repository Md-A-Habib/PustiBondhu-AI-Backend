package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.core.food.entity.Food;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.util.Objects;

/**
 * Represents a recommended swap: an alternative {@link Food} for another food,
 * optionally tied to a {@link MedicalCondition}. Moved from Core to Health
 * because it references medical_conditions.
 *
 * <p>Module: HEALTH | Table: food_alternatives | Migration: V100 | Author: Ahsan</p>
 */
@Entity
@Table(name = "food_alternatives")
public class FoodAlternative {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Original food to be replaced (FK -> foods.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "food_id", nullable = false)
    private Food food;

    /** Recommended alternative food (FK -> foods.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "alternative_food_id", nullable = false)
    private Food alternativeFood;

    /** Medical condition this swap applies to (FK -> medical_conditions.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "condition_id")
    private MedicalCondition condition;

    /** Reason for the swap recommendation (optional). */
    @Column(name = "reason", columnDefinition = "TEXT")
    private String reason;

    /** Required by JPA. */
    public FoodAlternative() {
    }

    /** Creates a fully populated instance. */
    public FoodAlternative(Long id, Food food, Food alternativeFood,
                           MedicalCondition condition, String reason) {
        this.id = id;
        this.food = food;
        this.alternativeFood = alternativeFood;
        this.condition = condition;
        this.reason = reason;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Food getFood() {
        return food;
    }

    public void setFood(Food food) {
        this.food = food;
    }

    public Food getAlternativeFood() {
        return alternativeFood;
    }

    public void setAlternativeFood(Food alternativeFood) {
        this.alternativeFood = alternativeFood;
    }

    public MedicalCondition getCondition() {
        return condition;
    }

    public void setCondition(MedicalCondition condition) {
        this.condition = condition;
    }

    public String getReason() {
        return reason;
    }

    public void setReason(String reason) {
        this.reason = reason;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof FoodAlternative that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "FoodAlternative{id=" + id
                + ", reason='" + reason + '\'' + '}';
    }
}