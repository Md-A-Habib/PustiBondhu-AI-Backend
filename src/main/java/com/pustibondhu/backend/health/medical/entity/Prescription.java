package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.core.user.entity.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.LocalDate;
import java.util.Objects;

/**
 * Represents a doctor's prescription of a user, optionally linked to an
 * uploaded {@link MedicalDocument}.
 *
 * <p>Module: HEALTH | Table: prescriptions | Migration: V101 | Author: Ahsan</p>
 */
@Entity
@Table(name = "prescriptions")
public class Prescription {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Owner of this prescription (FK -> users.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /** Uploaded source document (FK -> medical_documents.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "document_id")
    private MedicalDocument document;

    /** Doctor name (optional). */
    @Column(name = "doctor_name", length = 150)
    private String doctorName;

    /** Prescription date (optional). */
    @Column(name = "prescribed_on")
    private LocalDate prescribedOn;

    /** Validity end date (optional). */
    @Column(name = "valid_until")
    private LocalDate validUntil;

    /** Required by JPA. */
    public Prescription() {
    }

    /** Creates a fully populated instance. */
    public Prescription(Long id, User user, MedicalDocument document, String doctorName,
                        LocalDate prescribedOn, LocalDate validUntil) {
        this.id = id;
        this.user = user;
        this.document = document;
        this.doctorName = doctorName;
        this.prescribedOn = prescribedOn;
        this.validUntil = validUntil;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public User getUser() {
        return user;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public MedicalDocument getDocument() {
        return document;
    }

    public void setDocument(MedicalDocument document) {
        this.document = document;
    }

    public String getDoctorName() {
        return doctorName;
    }

    public void setDoctorName(String doctorName) {
        this.doctorName = doctorName;
    }

    public LocalDate getPrescribedOn() {
        return prescribedOn;
    }

    public void setPrescribedOn(LocalDate prescribedOn) {
        this.prescribedOn = prescribedOn;
    }

    public LocalDate getValidUntil() {
        return validUntil;
    }

    public void setValidUntil(LocalDate validUntil) {
        this.validUntil = validUntil;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Prescription that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "Prescription{id=" + id
                + ", doctorName='" + doctorName + '\''
                + ", prescribedOn=" + prescribedOn
                + ", validUntil=" + validUntil + '}';
    }
}