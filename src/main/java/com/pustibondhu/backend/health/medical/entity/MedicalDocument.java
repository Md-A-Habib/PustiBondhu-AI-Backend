package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.core.user.entity.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.Instant;
import java.time.LocalDate;
import java.util.Objects;

/**
 * Represents an uploaded medical document (prescription or lab report).
 * Replaces the old MedicalReport stub. Supports soft delete via deleted_at.
 *
 * <p>Module: HEALTH | Table: medical_documents | Migration: V101 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>document_type: PRESCRIPTION, LAB_REPORT</li>
 *   <li>storage_key: encrypted storage key of the uploaded file</li>
 * </ul>
 */
@Entity
@Table(name = "medical_documents")
public class MedicalDocument {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Owner of this document (FK -> users.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /** Document type: PRESCRIPTION or LAB_REPORT. */
    @Column(name = "document_type", nullable = false, length = 20)
    private String documentType;

    /** Encrypted storage key of the file. */
    @Column(name = "storage_key", nullable = false, length = 500)
    private String storageKey;

    /** Original uploaded file name (optional). */
    @Column(name = "original_filename", length = 255)
    private String originalFilename;

    /** File MIME type (optional). */
    @Column(name = "mime_type", length = 100)
    private String mimeType;

    /** File size in bytes (optional). */
    @Column(name = "size_bytes")
    private Long sizeBytes;

    /** SHA-256 checksum of the file, CHAR(64) (optional). */
    @Column(name = "checksum_sha256", length = 64, columnDefinition = "CHAR(64)")
    private String checksumSha256;

    /** Date written on the document (optional). */
    @Column(name = "document_date")
    private LocalDate documentDate;

    /** Soft delete timestamp (TIMESTAMPTZ). Null means not deleted. */
    @Column(name = "deleted_at", columnDefinition = "TIMESTAMPTZ")
    private Instant deletedAt;

    /** Required by JPA. */
    public MedicalDocument() {
    }

    /** Creates a fully populated instance. */
    public MedicalDocument(Long id, User user, String documentType, String storageKey,
                           String originalFilename, String mimeType, Long sizeBytes,
                           String checksumSha256, LocalDate documentDate, Instant deletedAt) {
        this.id = id;
        this.user = user;
        this.documentType = documentType;
        this.storageKey = storageKey;
        this.originalFilename = originalFilename;
        this.mimeType = mimeType;
        this.sizeBytes = sizeBytes;
        this.checksumSha256 = checksumSha256;
        this.documentDate = documentDate;
        this.deletedAt = deletedAt;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public User getUser() {
        return user;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public String getDocumentType() {
        return documentType;
    }

    public void setDocumentType(String documentType) {
        this.documentType = documentType;
    }

    public String getStorageKey() {
        return storageKey;
    }

    public void setStorageKey(String storageKey) {
        this.storageKey = storageKey;
    }

    public String getOriginalFilename() {
        return originalFilename;
    }

    public void setOriginalFilename(String originalFilename) {
        this.originalFilename = originalFilename;
    }

    public String getMimeType() {
        return mimeType;
    }

    public void setMimeType(String mimeType) {
        this.mimeType = mimeType;
    }

    public Long getSizeBytes() {
        return sizeBytes;
    }

    public void setSizeBytes(Long sizeBytes) {
        this.sizeBytes = sizeBytes;
    }

    public String getChecksumSha256() {
        return checksumSha256;
    }

    public void setChecksumSha256(String checksumSha256) {
        this.checksumSha256 = checksumSha256;
    }

    public LocalDate getDocumentDate() {
        return documentDate;
    }

    public void setDocumentDate(LocalDate documentDate) {
        this.documentDate = documentDate;
    }

    public Instant getDeletedAt() {
        return deletedAt;
    }

    public void setDeletedAt(Instant deletedAt) {
        this.deletedAt = deletedAt;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof MedicalDocument that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "MedicalDocument{id=" + id
                + ", documentType='" + documentType + '\''
                + ", originalFilename='" + originalFilename + '\''
                + ", mimeType='" + mimeType + '\''
                + ", sizeBytes=" + sizeBytes
                + ", documentDate=" + documentDate
                + ", deletedAt=" + deletedAt + '}';
    }
}