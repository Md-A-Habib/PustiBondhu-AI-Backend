package com.pustibondhu.backend.health.medical.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.util.Objects;

/**
 * Junction entity mapping a brand {@link Medicine} to a generic active
 * {@link DrugIngredient}, with the ingredient amount.
 *
 * <p>Module: HEALTH | Table: medicine_ingredients | Migration: V100 | Author: Ahsan</p>
 */
@Entity
@Table(name = "medicine_ingredients")
public class MedicineIngredient {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Brand medicine (FK -> medicines.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "medicine_id", nullable = false)
    private Medicine medicine;

    /** Active ingredient (FK -> drug_ingredients.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "ingredient_id", nullable = false)
    private DrugIngredient ingredient;

    /** Ingredient strength/amount in this medicine (optional). */
    @Column(name = "amount", length = 40)
    private String amount;

    /** Required by JPA. */
    public MedicineIngredient() {
    }

    /** Creates a fully populated instance. */
    public MedicineIngredient(Long id, Medicine medicine, DrugIngredient ingredient, String amount) {
        this.id = id;
        this.medicine = medicine;
        this.ingredient = ingredient;
        this.amount = amount;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Medicine getMedicine() {
        return medicine;
    }

    public void setMedicine(Medicine medicine) {
        this.medicine = medicine;
    }

    public DrugIngredient getIngredient() {
        return ingredient;
    }

    public void setIngredient(DrugIngredient ingredient) {
        this.ingredient = ingredient;
    }

    public String getAmount() {
        return amount;
    }

    public void setAmount(String amount) {
        this.amount = amount;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof MedicineIngredient that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "MedicineIngredient{id=" + id
                + ", amount='" + amount + '\'' + '}';
    }
}