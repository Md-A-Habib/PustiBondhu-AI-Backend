package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.core.user.entity.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.LocalDate;
import java.util.Objects;

/**
 * Represents a user's active medication regimen, used for food-drug
 * interaction safety checks. The medicine can be a listed {@link Medicine}
 * or a custom (unlisted) brand name, and may link to a {@link PrescriptionItem}.
 *
 * <p>Module: HEALTH | Table: user_medications | Migration: V101 | Author: Ahsan</p>
 */
@Entity
@Table(name = "user_medications")
public class UserMedication {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Owner of this regimen (FK -> users.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /** Listed brand medicine (FK -> medicines.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "medicine_id")
    private Medicine medicine;

    /** Unlisted brand name (optional). */
    @Column(name = "custom_name", length = 150)
    private String customName;

    /** Source prescription item (FK -> prescription_items.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "prescription_item_id")
    private PrescriptionItem prescriptionItem;

    /** Dosage string (optional). */
    @Column(name = "dosage", length = 100)
    private String dosage;

    /** Frequency string (optional). */
    @Column(name = "frequency", length = 100)
    private String frequency;

    /** Regimen start date (optional). */
    @Column(name = "start_date")
    private LocalDate startDate;

    /** Regimen end date (optional). */
    @Column(name = "end_date")
    private LocalDate endDate;

    /** Whether the regimen is currently active. */
    @Column(name = "is_active", nullable = false)
    private Boolean isActive;

    /** Required by JPA. */
    public UserMedication() {
    }

    /** Creates a fully populated instance. */
    public UserMedication(Long id, User user, Medicine medicine, String customName,
                          PrescriptionItem prescriptionItem, String dosage, String frequency,
                          LocalDate startDate, LocalDate endDate, Boolean isActive) {
        this.id = id;
        this.user = user;
        this.medicine = medicine;
        this.customName = customName;
        this.prescriptionItem = prescriptionItem;
        this.dosage = dosage;
        this.frequency = frequency;
        this.startDate = startDate;
        this.endDate = endDate;
        this.isActive = isActive;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public User getUser() {
        return user;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public Medicine getMedicine() {
        return medicine;
    }

    public void setMedicine(Medicine medicine) {
        this.medicine = medicine;
    }

    public String getCustomName() {
        return customName;
    }

    public void setCustomName(String customName) {
        this.customName = customName;
    }

    public PrescriptionItem getPrescriptionItem() {
        return prescriptionItem;
    }

    public void setPrescriptionItem(PrescriptionItem prescriptionItem) {
        this.prescriptionItem = prescriptionItem;
    }

    public String getDosage() {
        return dosage;
    }

    public void setDosage(String dosage) {
        this.dosage = dosage;
    }

    public String getFrequency() {
        return frequency;
    }

    public void setFrequency(String frequency) {
        this.frequency = frequency;
    }

    public LocalDate getStartDate() {
        return startDate;
    }

    public void setStartDate(LocalDate startDate) {
        this.startDate = startDate;
    }

    public LocalDate getEndDate() {
        return endDate;
    }

    public void setEndDate(LocalDate endDate) {
        this.endDate = endDate;
    }

    public Boolean getIsActive() {
        return isActive;
    }

    public void setIsActive(Boolean isActive) {
        this.isActive = isActive;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof UserMedication that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "UserMedication{id=" + id
                + ", customName='" + customName + '\''
                + ", dosage='" + dosage + '\''
                + ", frequency='" + frequency + '\''
                + ", startDate=" + startDate
                + ", endDate=" + endDate
                + ", isActive=" + isActive + '}';
    }
}