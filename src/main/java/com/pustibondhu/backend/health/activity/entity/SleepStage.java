package com.pustibondhu.backend.health.activity.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.Instant;
import java.util.Objects;

/**
 * Represents one stage (AWAKE, LIGHT, DEEP, REM) within a {@link SleepSession}.
 * Child breakdown of a sleep session.
 *
 * <p>Module: HEALTH | Table: sleep_stages | Migration: V104 | Author: Ahsan</p>
 */
@Entity
@Table(name = "sleep_stages")
public class SleepStage {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Parent sleep session (FK -> sleep_sessions.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "sleep_session_id", nullable = false)
    private SleepSession sleepSession;

    /** Sleep stage: AWAKE, LIGHT, DEEP, or REM. */
    @Column(name = "stage", nullable = false, length = 12)
    private String stage;

    /** Stage start time (TIMESTAMPTZ). */
    @Column(name = "start_time", nullable = false, columnDefinition = "TIMESTAMPTZ")
    private Instant startTime;

    /** Stage end time (TIMESTAMPTZ). */
    @Column(name = "end_time", nullable = false, columnDefinition = "TIMESTAMPTZ")
    private Instant endTime;

    /** Required by JPA. */
    public SleepStage() {
    }

    /** Creates a fully populated instance. */
    public SleepStage(Long id, SleepSession sleepSession, String stage,
                      Instant startTime, Instant endTime) {
        this.id = id;
        this.sleepSession = sleepSession;
        this.stage = stage;
        this.startTime = startTime;
        this.endTime = endTime;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public SleepSession getSleepSession() {
        return sleepSession;
    }

    public void setSleepSession(SleepSession sleepSession) {
        this.sleepSession = sleepSession;
    }

    public String getStage() {
        return stage;
    }

    public void setStage(String stage) {
        this.stage = stage;
    }

    public Instant getStartTime() {
        return startTime;
    }

    public void setStartTime(Instant startTime) {
        this.startTime = startTime;
    }

    public Instant getEndTime() {
        return endTime;
    }

    public void setEndTime(Instant endTime) {
        this.endTime = endTime;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof SleepStage that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "SleepStage{id=" + id
                + ", stage='" + stage + '\''
                + ", startTime=" + startTime
                + ", endTime=" + endTime + '}';
    }
}