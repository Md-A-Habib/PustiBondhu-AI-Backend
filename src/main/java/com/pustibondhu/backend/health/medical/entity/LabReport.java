package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.core.user.entity.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.LocalDate;
import java.util.Objects;

/**
 * Container for lab result entries of a user, optionally linked to an
 * uploaded {@link MedicalDocument}.
 *
 * <p>Module: HEALTH | Table: lab_reports | Migration: V102 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>review_status: PENDING_REVIEW, CONFIRMED</li>
 * </ul>
 */
@Entity
@Table(name = "lab_reports")
public class LabReport {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Owner of this report (FK -> users.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /** Uploaded source document (FK -> medical_documents.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "document_id")
    private MedicalDocument document;

    /** Diagnostic center name (optional). */
    @Column(name = "lab_name", length = 150)
    private String labName;

    /** Report date. */
    @Column(name = "report_date", nullable = false)
    private LocalDate reportDate;

    /** Ordering physician (optional). */
    @Column(name = "ordered_by", length = 150)
    private String orderedBy;

    /** Review status: PENDING_REVIEW or CONFIRMED. */
    @Column(name = "review_status", nullable = false, length = 15)
    private String reviewStatus;

    /** Required by JPA. */
    public LabReport() {
    }

    /** Creates a fully populated instance. */
    public LabReport(Long id, User user, MedicalDocument document, String labName,
                     LocalDate reportDate, String orderedBy, String reviewStatus) {
        this.id = id;
        this.user = user;
        this.document = document;
        this.labName = labName;
        this.reportDate = reportDate;
        this.orderedBy = orderedBy;
        this.reviewStatus = reviewStatus;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public User getUser() {
        return user;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public MedicalDocument getDocument() {
        return document;
    }

    public void setDocument(MedicalDocument document) {
        this.document = document;
    }

    public String getLabName() {
        return labName;
    }

    public void setLabName(String labName) {
        this.labName = labName;
    }

    public LocalDate getReportDate() {
        return reportDate;
    }

    public void setReportDate(LocalDate reportDate) {
        this.reportDate = reportDate;
    }

    public String getOrderedBy() {
        return orderedBy;
    }

    public void setOrderedBy(String orderedBy) {
        this.orderedBy = orderedBy;
    }

    public String getReviewStatus() {
        return reviewStatus;
    }

    public void setReviewStatus(String reviewStatus) {
        this.reviewStatus = reviewStatus;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof LabReport that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "LabReport{id=" + id
                + ", labName='" + labName + '\''
                + ", reportDate=" + reportDate
                + ", orderedBy='" + orderedBy + '\''
                + ", reviewStatus='" + reviewStatus + '\'' + '}';
    }
}