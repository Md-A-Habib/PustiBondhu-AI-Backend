package com.pustibondhu.backend.health.medical.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import java.util.Objects;

/**
 * Represents one medicine item prescribed by a doctor within a {@link Prescription}.
 * The matched brand {@link Medicine} is optional, since the raw name written on
 * the prescription may not be matched yet.
 *
 * <p>Module: HEALTH | Table: prescription_items | Migration: V101 | Author: Ahsan</p>
 */
@Entity
@Table(name = "prescription_items")
public class PrescriptionItem {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Parent prescription (FK -> prescriptions.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "prescription_id", nullable = false)
    private Prescription prescription;

    /** Matched brand medicine (FK -> medicines.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "medicine_id")
    private Medicine medicine;

    /** Raw medicine name as written on the prescription. */
    @Column(name = "medicine_name_raw", nullable = false, length = 150)
    private String medicineNameRaw;

    /** Dosage instructions (optional). */
    @Column(name = "dosage", length = 100)
    private String dosage;

    /** Frequency, e.g. 1-0-1 (optional). */
    @Column(name = "frequency", length = 100)
    private String frequency;

    /** Duration in days, SMALLINT (optional). */
    @JdbcTypeCode(SqlTypes.SMALLINT)
    @Column(name = "duration_days")
    private Integer durationDays;

    /** Extra instructions, e.g. After meal (optional). */
    @Column(name = "instructions", columnDefinition = "TEXT")
    private String instructions;

    /** Required by JPA. */
    public PrescriptionItem() {
    }

    /** Creates a fully populated instance. */
    public PrescriptionItem(Long id, Prescription prescription, Medicine medicine,
                            String medicineNameRaw, String dosage, String frequency,
                            Integer durationDays, String instructions) {
        this.id = id;
        this.prescription = prescription;
        this.medicine = medicine;
        this.medicineNameRaw = medicineNameRaw;
        this.dosage = dosage;
        this.frequency = frequency;
        this.durationDays = durationDays;
        this.instructions = instructions;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Prescription getPrescription() {
        return prescription;
    }

    public void setPrescription(Prescription prescription) {
        this.prescription = prescription;
    }

    public Medicine getMedicine() {
        return medicine;
    }

    public void setMedicine(Medicine medicine) {
        this.medicine = medicine;
    }

    public String getMedicineNameRaw() {
        return medicineNameRaw;
    }

    public void setMedicineNameRaw(String medicineNameRaw) {
        this.medicineNameRaw = medicineNameRaw;
    }

    public String getDosage() {
        return dosage;
    }

    public void setDosage(String dosage) {
        this.dosage = dosage;
    }

    public String getFrequency() {
        return frequency;
    }

    public void setFrequency(String frequency) {
        this.frequency = frequency;
    }

    public Integer getDurationDays() {
        return durationDays;
    }

    public void setDurationDays(Integer durationDays) {
        this.durationDays = durationDays;
    }

    public String getInstructions() {
        return instructions;
    }

    public void setInstructions(String instructions) {
        this.instructions = instructions;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof PrescriptionItem that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "PrescriptionItem{id=" + id
                + ", medicineNameRaw='" + medicineNameRaw + '\''
                + ", dosage='" + dosage + '\''
                + ", frequency='" + frequency + '\''
                + ", durationDays=" + durationDays
                + ", instructions='" + instructions + '\'' + '}';
    }
}