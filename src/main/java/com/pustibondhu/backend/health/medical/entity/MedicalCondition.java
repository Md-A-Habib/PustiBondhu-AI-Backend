package com.pustibondhu.backend.health.medical.entity;

import com.pustibondhu.backend.health.common.entity.KnowledgeSource;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.util.Objects;

/**
 * Represents a medical condition definition (ICD-10).
 * Referenced by health rules.
 *
 * <p>Module: HEALTH | Table: medical_conditions | Migration: V100 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>code: unique ICD-10 code</li>
 *   <li>category: METABOLIC, CARDIAC, RENAL</li>
 * </ul>
 */
@Entity
@Table(name = "medical_conditions")
public class MedicalCondition {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Unique ICD-10 code. */
    @Column(name = "code", nullable = false, unique = true, length = 20)
    private String code;

    /** English condition name. */
    @Column(name = "name_en", nullable = false, length = 150)
    private String nameEn;

    /** Bangla condition name. */
    @Column(name = "name_bn", nullable = false, length = 150)
    private String nameBn;

    /** Category: METABOLIC, CARDIAC, RENAL. */
    @Column(name = "category", nullable = false, length = 60)
    private String category;

    /** Knowledge source of this definition (FK -> knowledge_sources.id, optional). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "source_id")
    private KnowledgeSource source;

    /** Required by JPA. */
    public MedicalCondition() {
    }

    /** Creates a fully populated instance. */
    public MedicalCondition(Long id, String code, String nameEn, String nameBn,
                            String category, KnowledgeSource source) {
        this.id = id;
        this.code = code;
        this.nameEn = nameEn;
        this.nameBn = nameBn;
        this.category = category;
        this.source = source;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
    }

    public String getNameEn() {
        return nameEn;
    }

    public void setNameEn(String nameEn) {
        this.nameEn = nameEn;
    }

    public String getNameBn() {
        return nameBn;
    }

    public void setNameBn(String nameBn) {
        this.nameBn = nameBn;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    public KnowledgeSource getSource() {
        return source;
    }

    public void setSource(KnowledgeSource source) {
        this.source = source;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof MedicalCondition that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "MedicalCondition{id=" + id
                + ", code='" + code + '\''
                + ", nameEn='" + nameEn + '\''
                + ", nameBn='" + nameBn + '\''
                + ", category='" + category + '\'' + '}';
    }
}