package com.pustibondhu.backend.health.medical.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.math.BigDecimal;
import java.util.Objects;

/**
 * Represents one lab value entry of a {@link LabReport} for a
 * {@link LabTestDefinition}, with status flag and plain-language explanation.
 * Reference low/high are snapshotted at entry time.
 *
 * <p>Module: HEALTH | Table: lab_results | Migration: V102 | Author: Ahsan</p>
 *
 * <ul>
 *   <li>flag: NORMAL, LOW, HIGH, CRITICAL</li>
 *   <li>explanation_source: RULE, AI</li>
 * </ul>
 */
@Entity
@Table(name = "lab_results")
public class LabResult {

    /** Primary key (BIGSERIAL, auto-generated by the database). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    /** Parent report (FK -> lab_reports.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "lab_report_id", nullable = false)
    private LabReport labReport;

    /** Lab test measured (FK -> lab_test_definitions.id). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "lab_test_id", nullable = false)
    private LabTestDefinition labTest;

    /** Numeric reading, NUMERIC(12,4) (optional). */
    @Column(name = "value_numeric", precision = 12, scale = 4)
    private BigDecimal valueNumeric;

    /** Textual value (optional). */
    @Column(name = "value_text", length = 100)
    private String valueText;

    /** Unit string (optional). */
    @Column(name = "unit", length = 30)
    private String unit;

    /** Snapshotted lower reference bound, NUMERIC(10,3) (optional). */
    @Column(name = "reference_low", precision = 10, scale = 3)
    private BigDecimal referenceLow;

    /** Snapshotted upper reference bound, NUMERIC(10,3) (optional). */
    @Column(name = "reference_high", precision = 10, scale = 3)
    private BigDecimal referenceHigh;

    /** Flag: NORMAL, LOW, HIGH, or CRITICAL (optional). */
    @Column(name = "flag", length = 10)
    private String flag;

    /** Plain-language summary (optional). */
    @Column(name = "explanation", columnDefinition = "TEXT")
    private String explanation;

    /** Explanation origin: RULE or AI (optional). */
    @Column(name = "explanation_source", length = 10)
    private String explanationSource;

    /** Required by JPA. */
    public LabResult() {
    }

    /** Creates a fully populated instance. */
    public LabResult(Long id, LabReport labReport, LabTestDefinition labTest,
                     BigDecimal valueNumeric, String valueText, String unit,
                     BigDecimal referenceLow, BigDecimal referenceHigh, String flag,
                     String explanation, String explanationSource) {
        this.id = id;
        this.labReport = labReport;
        this.labTest = labTest;
        this.valueNumeric = valueNumeric;
        this.valueText = valueText;
        this.unit = unit;
        this.referenceLow = referenceLow;
        this.referenceHigh = referenceHigh;
        this.flag = flag;
        this.explanation = explanation;
        this.explanationSource = explanationSource;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public LabReport getLabReport() {
        return labReport;
    }

    public void setLabReport(LabReport labReport) {
        this.labReport = labReport;
    }

    public LabTestDefinition getLabTest() {
        return labTest;
    }

    public void setLabTest(LabTestDefinition labTest) {
        this.labTest = labTest;
    }

    public BigDecimal getValueNumeric() {
        return valueNumeric;
    }

    public void setValueNumeric(BigDecimal valueNumeric) {
        this.valueNumeric = valueNumeric;
    }

    public String getValueText() {
        return valueText;
    }

    public void setValueText(String valueText) {
        this.valueText = valueText;
    }

    public String getUnit() {
        return unit;
    }

    public void setUnit(String unit) {
        this.unit = unit;
    }

    public BigDecimal getReferenceLow() {
        return referenceLow;
    }

    public void setReferenceLow(BigDecimal referenceLow) {
        this.referenceLow = referenceLow;
    }

    public BigDecimal getReferenceHigh() {
        return referenceHigh;
    }

    public void setReferenceHigh(BigDecimal referenceHigh) {
        this.referenceHigh = referenceHigh;
    }

    public String getFlag() {
        return flag;
    }

    public void setFlag(String flag) {
        this.flag = flag;
    }

    public String getExplanation() {
        return explanation;
    }

    public void setExplanation(String explanation) {
        this.explanation = explanation;
    }

    public String getExplanationSource() {
        return explanationSource;
    }

    public void setExplanationSource(String explanationSource) {
        this.explanationSource = explanationSource;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof LabResult that)) return false;
        return id != null && Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "LabResult{id=" + id
                + ", valueNumeric=" + valueNumeric
                + ", valueText='" + valueText + '\''
                + ", unit='" + unit + '\''
                + ", referenceLow=" + referenceLow
                + ", referenceHigh=" + referenceHigh
                + ", flag='" + flag + '\''
                + ", explanationSource='" + explanationSource + '\'' + '}';
    }
}